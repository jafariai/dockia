import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

export function formatBytes(bytes: number): string {
  if (!bytes) return "0 B";
  const units = ["B", "KB", "MB", "GB"];
  const i = Math.floor(Math.log(bytes) / Math.log(1024));
  return `${(bytes / Math.pow(1024, i)).toFixed(1)} ${units[i]}`;
}

/**
 * Sandbox attribute for any document-preview iframe — the single source of
 * truth for this security boundary. `allow-scripts` only for interactive docs;
 * `allow-same-origin` is NEVER granted, so the frame stays an opaque origin
 * isolated from the app (no cookies/JWT/localStorage access).
 */
export function previewSandbox(interactive: boolean): string {
  return interactive ? "allow-scripts" : "";
}

/**
 * Copy text to the clipboard, returning whether it succeeded. Guards the
 * Clipboard API (absent over plain HTTP on a non-localhost origin) and falls
 * back to a hidden-textarea + execCommand so it never throws.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    /* fall through to the legacy path */
  }
  try {
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.focus();
    ta.select();
    const ok = document.execCommand("copy");
    ta.remove();
    return ok;
  } catch {
    return false;
  }
}

export function initials(name?: string | null): string {
  if (!name) return "?";
  return name
    .split(" ")
    .map((p) => p[0])
    .filter(Boolean)
    .slice(0, 2)
    .join("")
    .toUpperCase();
}
